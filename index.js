// نص/رقم → قروش (integer). null لو فاضي أو مش رقم (مفيش "0" ضمني).
function bostaPiastres(v) {
  if (v === null || v === undefined) return null;
  const s = String(v).replace(/,/g, '').trim();
  if (!s) return null;
  const n = Number(s);
  return Number.isFinite(n) ? Math.round(n * 100) : null;
}
