function courierBalance(node, label) {
  const b = bostaBalance(node).balanceP;
  if (b === null) throw new Error(`${label}: شوبيفاي ما رجّعتش إجمالي الأوردر أو المدفوع (مش قادرين نحسب المستحق) — الأمر اتوقف`);
  return b / 100;
}
